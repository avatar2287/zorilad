export function scrollById(id: string) {
  return scrolls.find((item) => item.id === id) ?? scrolls[0];
}

export function previousScroll(id: string) {
  const index = scrolls.findIndex((item) => item.id === id);
  if (index <= 0) return null;
  return scrolls[index - 1] ?? null;
}

export function nextScroll(id: string) {
  const index = scrolls.findIndex((item) => item.id === id);
  if (index < 0 || index >= scrolls.length - 1) return null;
  return scrolls[index + 1] ?? null;
}

export function isUnlocked(id: string, completed: string[]) {
  const prev = previousScroll(id);
  if (!prev) return true;
  return completed.includes(prev.id);
}

export function currentScroll(completed: string[]) {
  return scrolls.find((item) => !completed.includes(item.id)) ?? scrolls[scrolls.length - 1]!;
}

export function artFor(scroll: Scroll) {
  if (scroll.art === "seal") return "/aurlis/seal.jpg";
  if (scroll.art === "home") return "/aurlis/home.jpg";
  return "/aurlis/scroll.jpg";
}

