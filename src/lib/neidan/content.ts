export function practiceById(id: string) {
  return practices.find((item) => item.id === id) ?? practices[0];
}

export function scrollById(id: string) {
  return scrolls.find((item) => item.id === id) ?? scrolls[0];
}

export function fieldById(id: string) {
  return fields.find((item) => item.id === id) ?? fields[0];
}

export function practiceOfDay(now = new Date()) {
  const start = Date.UTC(2026, 0, 1);
  const day = Math.floor((now.getTime() - start) / 86_400_000);
  const pool = practices.filter((item) => item.id !== "three-breaths");
  const index = ((day % pool.length) + pool.length) % pool.length;
  return pool[index]!;
}

export function formatDay(now = new Date()) {
  return new Intl.DateTimeFormat("ru", {
    weekday: "long",
    day: "numeric",
    month: "long",
  }).format(now);
}
